"""Промпт для пояснения выдачи — шаг generation в RAG (КТ2).

API передаёт сюда запрос пользователя и выдачу BM25, а сообщения из build_messages
отправляет локальной LLM (app/llm/client.py). Ответ модели API проверяет и
превращает в поле answer (формат — spec/tech/architecture.md, раздел 4.5).

Что модель должна вернуть — только абзацы о патентах, без вступления и заключения:
- по абзацу на каждый переданный патент в порядке выдачи; абзац начинается с "[ID] "
  и вердикта: ANALOG_VERDICT «Аналог.» (то же назначение; дальше — что общего с идеей
  и чем патент отличается) или NOT_ANALOG_VERDICT «Не аналог.» (дальше — для чего
  предназначен патент); вердикт разбирает функция verdict;
- только факты из рефератов; ссылки только вида [ID] и только на переданные id;
- простой текст без Markdown, без юридических выводов о новизне и патентоспособности.

Вводный абзац и дисклеймер «Это первичный поиск аналогов, а не юридическое заключение
о новизне или патентоспособности.» добавляет API, а не модель. Если у всех переданных
патентов вердикт «Не аналог.», API сообщает, что аналогов в корпусе не найдено (как на
слайде курса: если нужных сведений нет — сообщить об этом).

Схема ожидаемого ответа модели (не реальный вывод):

    [DEMO-002] Аналог. <что у патента общего с идеей>. <чем патент отличается>.

    [DEMO-001] Не аналог. <для чего предназначен патент>.

Почему вердикт у каждого патента, а не один общий отказ: промпт «сначала реши, есть ли
аналог, иначе ответь АНАЛОГОВ НЕТ» на qwen2.5:7b отказывал даже там, где все пять
рефератов — аналоги (spec/tech/rag.md, раздел 13.8).

В контекст идут первые MAX_CONTEXT_DOCS = 5 результатов: поэтому главная метрика
поиска — Recall@5 (spec/tech/rag.md, раздел 9). Остальные результаты выдачи
показываются в карточках без пояснения.
"""

from __future__ import annotations

import re
from collections.abc import Mapping, Sequence
from typing import Any

MAX_CONTEXT_DOCS = 5
"""Сколько первых результатов выдачи попадает в промпт."""

ANALOG_VERDICT = "Аналог."
"""Вердикт в начале абзаца о патенте того же назначения, что идея."""

NOT_ANALOG_VERDICT = "Не аналог."
"""Вердикт в начале абзаца о патенте другого назначения; если он у всех патентов — аналогов нет."""

_VERDICT = re.compile(r"\s*(не\s+)?аналог(?!\w)", re.IGNORECASE)

SYSTEM_PROMPT = """\
Ты помогаешь изобретателю провести первичный поиск аналогов среди патентов Российской Федерации.
Тебе дают описание идеи пользователя и рефераты найденных патентов. Каждый реферат начинается с идентификатора патента в квадратных скобках.

Патент — аналог идеи, если это устройство или способ того же назначения: для того же применения и для той же основной задачи. Отличия в деталях не мешают патенту быть аналогом — о них нужно написать как об отличиях. Совпадения отдельных слов недостаточно: патент с другим назначением — не аналог.

Правила ответа:
1. Напиши по одному абзацу на каждый патент в том порядке, в котором они перечислены, и больше ничего: без вступления и без заключения.
2. Абзац начинается с идентификатора в квадратных скобках точно в том виде, как он указан в списке, затем пробел и слово «Аналог.» или слова «Не аналог.»; текст абзаца продолжается в той же строке.
3. После «Аналог.» — два коротких предложения. Первое — что у патента общего с идеей. Второе — чем патент отличается: что в нём есть сверх идеи или какой признак идеи в реферате не упоминается.
4. После «Не аналог.» — одно предложение: для чего предназначен патент.
5. Опирайся только на приведённые рефераты. Не придумывай номера патентов, названия, числа, характеристики и факты, которых в рефератах нет. Номера патентов, которых нет в списке, не упоминай.
6. Не утверждай, что патент не решает задачу идеи или чего-то не умеет, если в реферате об этом прямо не сказано.
7. Не пересказывай идею пользователя и не повторяй идентификатор внутри абзаца.
8. Пиши по-русски простым текстом без Markdown: без заголовков, списков, таблиц и выделения.
9. Не делай юридических выводов: не оценивай новизну, патентоспособность и нарушение чужих прав.
10. Абзацы разделяй одной пустой строкой.
"""

USER_PROMPT_TEMPLATE = """\
Идея пользователя:
{query}

Найденные патенты ({count}), по убыванию сходства с идеей:

{context}

Напиши по абзацу на каждый патент в порядке: {ids}. Каждый абзац начинается с «[идентификатор] Аналог.» или «[идентификатор] Не аналог.»."""

CONTEXT_ITEM_TEMPLATE = """\
[{id}] {title}
МПК: {ipc}
Год публикации: {year}
Реферат: {abstract}"""


def build_messages(query: str, results: Sequence[Mapping[str, Any]]) -> list[dict[str, str]]:
    """Собирает сообщения для OpenAI-совместимого /chat/completions.

    Берёт первые MAX_CONTEXT_DOCS результатов в порядке выдачи. Используются поля
    контракта id, title, abstract, ipc, year; score в промпт не передаётся. Пробелы
    и переносы строк внутри названия и реферата схлопываются в один пробел.

    Args:
        query: запрос пользователя (как в поле query ответа API).
        results: выдача /search — словари с полями контракта
            (id, title, abstract, score, ipc, year), по убыванию score.

    Returns:
        [{"role": "system", "content": SYSTEM_PROMPT},
         {"role": "user", "content": <запрос и рефераты>}].

    Raises:
        ValueError: если results пуст — тогда LLM не вызывается, answer = NO_RESULTS_ANSWER.

    Example:
        >>> results = [{
        ...     "id": "DEMO-003",
        ...     "title": "Беспроводной датчик влажности почвы с автономным питанием",
        ...     "abstract": "Изобретение относится к измерительной технике, а именно к средствам контроля влажности почвы.",
        ...     "score": 4.31,
        ...     "ipc": ["G01N 33/24", "G01N 27/22", "H04W 4/38"],
        ...     "year": 2023,
        ... }]
        >>> messages = build_messages("Нужен беспроводной датчик влажности почвы", results)
        >>> [message["role"] for message in messages]
        ['system', 'user']
        >>> print(messages[1]["content"])
        Идея пользователя:
        Нужен беспроводной датчик влажности почвы
        <BLANKLINE>
        Найденные патенты (1), по убыванию сходства с идеей:
        <BLANKLINE>
        [DEMO-003] Беспроводной датчик влажности почвы с автономным питанием
        МПК: G01N 33/24, G01N 27/22, H04W 4/38
        Год публикации: 2023
        Реферат: Изобретение относится к измерительной технике, а именно к средствам контроля влажности почвы.
        <BLANKLINE>
        Напиши по абзацу на каждый патент в порядке: [DEMO-003]. Каждый абзац начинается с «[идентификатор] Аналог.» или «[идентификатор] Не аналог.».
    """
    if not results:
        raise ValueError("results пуст: при пустой выдаче LLM не вызывается, answer = NO_RESULTS_ANSWER")
    docs = list(results)[:MAX_CONTEXT_DOCS]
    context = "\n\n".join(
        CONTEXT_ITEM_TEMPLATE.format(
            id=doc["id"],
            title=" ".join(str(doc["title"]).split()),
            ipc=", ".join(doc["ipc"]),
            year=doc["year"],
            abstract=" ".join(str(doc["abstract"]).split()),
        )
        for doc in docs
    )
    user_content = USER_PROMPT_TEMPLATE.format(
        query=query.strip(),
        count=len(docs),
        context=context,
        ids=", ".join(f"[{doc['id']}]" for doc in docs),
    )
    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": user_content},
    ]


def verdict(text: str) -> bool | None:
    """Вердикт абзаца о патенте: True — «Аналог.», False — «Не аналог.», None — вердикта нет.

    text — абзац после "[ID] ". Регистр, пробелы и знак после вердикта (точка, двоеточие,
    тире) не важны; «Аналогичный…» и «Аналоги…» вердиктом не считаются.

    Example:
        >>> verdict("Аналог. Тоже паровой утюг."), verdict("не аналог: это холодильник."), verdict("Аналогичный утюг.")
        (True, False, None)
    """
    match = _VERDICT.match(text)
    if match is None:
        return None
    return match.group(1) is None
