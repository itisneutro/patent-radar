"""Черновик промпта для пояснения выдачи — шаг generation в RAG (КТ1).

На КТ2 API передаёт сюда запрос пользователя и выдачу BM25, а сообщения из
build_messages отправляет локальной LLM (app/llm/client.py, LLMClient.chat). На КТ1
эндпоинт /search LLM не вызывает: answer — заглушка с заранее составленным текстом.

Что модель должна вернуть (формат поля answer — spec/tech/architecture.md):
- простой текст без Markdown, абзацы разделены пустой строкой;
- первый абзац — вводный, без ссылок;
- затем по абзацу на каждый переданный патент, в порядке выдачи; абзац начинается
  с "[ID] ", например "[DEMO-002] ...";
- ссылки только вида [ID] и только на переданные id; номера и факты не выдумываются;
- без юридических выводов о новизне и патентоспособности;
- дисклеймер модель НЕ пишет: последний абзац «Это первичный поиск аналогов, а не
  юридическое заключение о новизне или патентоспособности.» добавляет API.

Схема ожидаемого ответа модели (не реальный вывод):

    <вводный абзац без ссылок>

    [DEMO-002] <чем патент похож на идею и чем отличается>

    [DEMO-001] <...>

В контекст идут первые MAX_CONTEXT_DOCS = 5 результатов: поэтому главная метрика
поиска — Recall@5 (spec/tech/rag.md, раздел 9). Остальные результаты выдачи
показываются в таблице без пояснения. Форматирование строк — не поиск, поэтому
build_messages реализована уже на КТ1.
"""

from __future__ import annotations

from collections.abc import Mapping, Sequence
from typing import Any

MAX_CONTEXT_DOCS = 5
"""Сколько первых результатов выдачи попадает в промпт."""

SYSTEM_PROMPT = """\
Ты помогаешь изобретателю провести первичный поиск аналогов среди патентов Российской Федерации.
Тебе дают описание идеи пользователя и рефераты найденных патентов. Каждый реферат начинается с идентификатора патента в квадратных скобках.

Правила ответа:
1. Опирайся только на приведённые рефераты. Не придумывай номера патентов, названия, характеристики и факты, которых в рефератах нет.
2. Пиши по-русски простым текстом без Markdown: без заголовков, списков, таблиц и выделения.
3. Первый абзац — одно-два предложения о том, что ниже идёт сравнение идеи с найденными патентами. В первом абзаце нет ссылок на патенты.
4. Дальше — по одному абзацу на каждый патент в том порядке, в котором они перечислены. Абзац начинается с идентификатора в квадратных скобках точно в том виде, как он указан в списке, и пробела. В абзаце два-три предложения: чем патент похож на идею и чем отличается от неё. Если патент почти не связан с идеей, так и напиши.
5. Ссылайся только на идентификаторы из списка и только в виде [идентификатор]. Номера патентов, которых нет в списке, не упоминай.
6. Не делай юридических выводов: не оценивай новизну, патентоспособность и нарушение чужих прав.
7. Не пиши заключение и предупреждение в конце — их добавит система.
8. Абзацы разделяй одной пустой строкой.
"""

USER_PROMPT_TEMPLATE = """\
Идея пользователя:
{query}

Найденные патенты ({count}), по убыванию сходства с идеей:

{context}

Напиши ответ по правилам: вводный абзац без ссылок, затем по абзацу на каждый патент в порядке: {ids}."""

CONTEXT_ITEM_TEMPLATE = """\
[{id}] {title}
МПК: {ipc}
Год публикации: {year}
Реферат: {abstract}"""

# Что проверяем на КТ2 — в API, после ответа модели (см. spec/tech/architecture.md):
# - ссылки ⊆ id: каждая метка [ID] в ответе есть среди id, переданных в промпт
#   (а значит, и в results); чужие метки API убирает;
# - структура: первый абзац без ссылок, затем абзацы, начинающиеся с "[ID] ", по одному
#   на каждый переданный патент и в порядке выдачи;
# - длина ответа: 2–3 предложения на патент; предел в символах подберём на демо-запросах,
#   слишком длинный ответ обрезаем по границе абзаца;
# - нет Markdown (#, *, нумерованных списков) и нет дисклеймера — его добавляет API;
# - ответ на русском; при недоступной LLM answer — фиксированный текст из контракта.
# Если модель регулярно нарушает формат, попробуем добавить в промпт пример ответа на
# демо-данных (few-shot) и сравним на демо-запросах.


def build_messages(query: str, results: Sequence[Mapping[str, Any]]) -> list[dict[str, str]]:
    """Собирает сообщения для OpenAI-совместимого /chat/completions.

    Берёт первые MAX_CONTEXT_DOCS результатов в порядке выдачи. Используются поля
    контракта id, title, abstract, ipc, year; score в промпт не передаётся. Пробелы
    и переносы строк внутри названия и реферата схлопываются в один пробел.

    Args:
        query: запрос пользователя (как в поле query ответа API).
        results: выдача /search — словари с полями контракта
            (id, title, abstract, score, ipc, year), по убыванию score.

    Returns:
        [{"role": "system", "content": SYSTEM_PROMPT},
         {"role": "user", "content": <запрос и рефераты>}].

    Raises:
        ValueError: если results пуст — тогда LLM не вызывается, answer = NO_RESULTS_ANSWER.

    Example:
        >>> results = [{
        ...     "id": "DEMO-003",
        ...     "title": "Беспроводной датчик влажности почвы с автономным питанием",
        ...     "abstract": "Изобретение относится к измерительной технике, а именно к средствам контроля влажности почвы.",
        ...     "score": 4.31,
        ...     "ipc": ["G01N 33/24", "G01N 27/22", "H04W 4/38"],
        ...     "year": 2023,
        ... }]
        >>> messages = build_messages("Нужен беспроводной датчик влажности почвы", results)
        >>> [message["role"] for message in messages]
        ['system', 'user']
        >>> print(messages[1]["content"])
        Идея пользователя:
        Нужен беспроводной датчик влажности почвы
        <BLANKLINE>
        Найденные патенты (1), по убыванию сходства с идеей:
        <BLANKLINE>
        [DEMO-003] Беспроводной датчик влажности почвы с автономным питанием
        МПК: G01N 33/24, G01N 27/22, H04W 4/38
        Год публикации: 2023
        Реферат: Изобретение относится к измерительной технике, а именно к средствам контроля влажности почвы.
        <BLANKLINE>
        Напиши ответ по правилам: вводный абзац без ссылок, затем по абзацу на каждый патент в порядке: [DEMO-003].
    """
    if not results:
        raise ValueError("results пуст: при пустой выдаче LLM не вызывается, answer = NO_RESULTS_ANSWER")
    docs = list(results)[:MAX_CONTEXT_DOCS]
    context = "\n\n".join(
        CONTEXT_ITEM_TEMPLATE.format(
            id=doc["id"],
            title=" ".join(str(doc["title"]).split()),
            ipc=", ".join(doc["ipc"]),
            year=doc["year"],
            abstract=" ".join(str(doc["abstract"]).split()),
        )
        for doc in docs
    )
    user_content = USER_PROMPT_TEMPLATE.format(
        query=query.strip(),
        count=len(docs),
        context=context,
        ids=", ".join(f"[{doc['id']}]" for doc in docs),
    )
    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": user_content},
    ]
