def is_demo_topic(query: str) -> bool:
    """Проверяет, относится ли запрос к демо-теме (есть хотя бы одна основа из списка)."""
    normalized = query.lower().replace("ё", "е")
    return any(stem in normalized for stem in DEMO_TOPIC_STEMS)


def normalize_ipc(code: str) -> str:
    """Приводит код или префикс МПК к виду для сравнения: без пробелов, прописными.

    Пример: «g01n 33» → «G01N33», «G01N 33/24» → «G01N33/24».
    """
    return "".join(code.split()).upper()


def matches_filters(
    patent: DemoPatent,
    year_from: int | None = None,
    year_to: int | None = None,
    ipc: str | None = None,
) -> bool:
    """Проверяет патент по фильтрам года публикации и префикса МПК.

    Фильтр со значением None не применяется. Префикс МПК подходит, если с него
    начинается хотя бы один код патента (без учёта регистра и пробелов).
    """
    if year_from is not None and patent["year"] < year_from:
        return False
    if year_to is not None and patent["year"] > year_to:
        return False
    if ipc is not None:
        prefix = normalize_ipc(ipc)
        return any(normalize_ipc(code).startswith(prefix) for code in patent["ipc"])
    return True


def build_answer(result_ids: Sequence[str]) -> str:
    """Собирает answer: вводный абзац, абзацы по патентам в порядке выдачи, дисклеймер.

    Для пустой выдачи возвращает NO_RESULTS_ANSWER.
    """
    if not result_ids:
        return NO_RESULTS_ANSWER
    paragraphs = [ANSWER_INTRO, *(EXPLANATIONS[patent_id] for patent_id in result_ids)]
    return "\n\n".join([*paragraphs, ANSWER_DISCLAIMER])


def search_stub(request: SearchRequest) -> SearchResponse:
    """Возвращает демонстрационный ответ POST /search по правилам заглушки КТ1."""
    scores = dict(DEMO_RANKING) if is_demo_topic(request.query) else {}
    found = [
        patent
        for patent in DEMO_PATENTS
        if patent["id"] in scores
        and matches_filters(patent, request.year_from, request.year_to, request.ipc)
    ]
    found.sort(key=lambda patent: (-scores[patent["id"]], patent["id"]))
    results = [
        PatentResult(**patent, score=scores[patent["id"]]) for patent in found[: request.top_k]
    ]
    return SearchResponse(
        query=request.query,
        results=results,
        answer=build_answer([result.id for result in results]),
    )
